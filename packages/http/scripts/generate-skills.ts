/**
 * Embeds `skills/<name>/**` into a TypeScript module.
 *
 * The skills are served from a Cloudflare Worker too, which has no filesystem,
 * so — like `@contentworker/docs` — they are embedded rather than read at
 * runtime. Run `pnpm --filter @contentworker/http generate:skills` after
 * editing skills/. The output is committed and a test fails if it drifts.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const skillsDir = join(here, '..', 'skills');
const out = join(here, '..', 'src', 'mcp', 'skills.generated.ts');

function walk(dir: string): string[] {
  return readdirSync(dir)
    .sort()
    .flatMap((name) => {
      const path = join(dir, name);
      return statSync(path).isDirectory() ? walk(path) : [path];
    });
}

export function buildSource(): string {
  const files = walk(skillsDir).map((path) => ({
    path: relative(skillsDir, path).split(sep).join('/'),
    body: readFileSync(path, 'utf8'),
  }));
  return [
    '// GENERATED by scripts/generate-skills.ts — do not edit.',
    '// Run `pnpm --filter @contentworker/http generate:skills` after editing skills/.',
    '',
    '/** Every published skill file, keyed by `<skill>/<path>`. */',
    'export const SKILL_FILES: Readonly<Record<string, string>> = {',
    ...files.map((f) => `  ${JSON.stringify(f.path)}: ${JSON.stringify(f.body)},`),
    '};',
    '',
  ].join('\n');
}

// Only when run as a script — the freshness test imports `buildSource` and must
// not rewrite the file it is checking.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(out, buildSource());
  console.log(`wrote ${out}`);
}
