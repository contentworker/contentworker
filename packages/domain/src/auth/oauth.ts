import { DomainError } from '../errors';
import { SCOPES } from './auth';

/**
 * OAuth 2.1 / MCP authorization primitives.
 *
 * This module is pure: no crypto, no clock, no storage. Anything needing a
 * digest (PKCE verification) takes the hash function as a parameter so the
 * domain keeps its "depends on nothing" guarantee.
 *
 * Deliberate OAuth 2.1 (draft-ietf-oauth-v2-1) restrictions enforced here:
 * - the implicit and password grants do not exist;
 * - PKCE is mandatory and only `S256` is accepted (`plain` is rejected);
 * - redirect URIs are compared by exact string match, never by prefix or
 *   wildcard, with the single documented exception of loopback ports.
 */

/** Grant types this authorization server issues. */
export const OAUTH_GRANT_TYPES = [
  'authorization_code',
  'refresh_token',
  'urn:ietf:params:oauth:grant-type:device_code',
] as const;
export type OAuthGrantType = (typeof OAUTH_GRANT_TYPES)[number];

/** The only PKCE method permitted. OAuth 2.1 removes `plain`. */
export const PKCE_METHOD_S256 = 'S256';

/** Token endpoint client authentication methods we support. */
export const OAUTH_AUTH_METHODS = ['none', 'client_secret_basic', 'client_secret_post'] as const;
export type OAuthAuthMethod = (typeof OAUTH_AUTH_METHODS)[number];

/** Error codes from RFC 6749 §4.1.2.1 / §5.2, RFC 8628 §3.5 and RFC 7591 §3.2.2. */
export type OAuthErrorCode =
  | 'invalid_request'
  | 'invalid_client'
  | 'invalid_grant'
  | 'invalid_scope'
  | 'unauthorized_client'
  | 'unsupported_grant_type'
  | 'unsupported_response_type'
  | 'access_denied'
  | 'server_error'
  | 'authorization_pending'
  | 'slow_down'
  | 'expired_token'
  | 'invalid_redirect_uri'
  | 'invalid_client_metadata';

/**
 * An OAuth protocol error. Carries the wire `error` code and the HTTP status
 * the token/registration endpoints must use — distinct from the generic
 * DomainError mapping, because OAuth pins specific status codes (e.g. an
 * `invalid_client` is 401, and `authorization_pending` is a 400 that clients
 * are expected to poll through).
 */
export class OAuthError extends DomainError {
  readonly error: OAuthErrorCode;
  readonly status: number;
  readonly errorDescription?: string;

  constructor(error: OAuthErrorCode, description?: string, status = 400) {
    super(`oauth_${error}`, description ?? error);
    this.error = error;
    this.status = status;
    this.errorDescription = description;
  }
}

/**
 * A registered OAuth client. Deliberately **not** space-scoped: clients arrive
 * through unauthenticated dynamic registration (RFC 7591), so they cannot be
 * trusted to name a space. The space is chosen by the human at consent time and
 * recorded on the grant.
 */
export interface OAuthClient {
  /** `client_id` — opaque, generated by us. */
  readonly id: string;
  readonly clientName: string;
  readonly redirectUris: readonly string[];
  readonly grantTypes: readonly OAuthGrantType[];
  /** Upper bound on what this client may ever request. */
  readonly scopes: readonly string[];
  readonly tokenEndpointAuthMethod: OAuthAuthMethod;
  /** Only set for confidential clients; the raw secret is never stored. */
  readonly hashedClientSecret?: string;
  readonly clientUri?: string;
  readonly logoUri?: string;
  readonly softwareId?: string;
  readonly createdAt: string;
}

/** Lifecycle of an authorization-code / device / refresh grant. */
export type OAuthGrantStatus = 'pending' | 'approved' | 'denied' | 'consumed' | 'revoked';

/** Which artifact a stored grant represents. */
export type OAuthGrantKind = 'code' | 'device' | 'refresh';

const KNOWN_SCOPES: readonly string[] = Object.values(SCOPES);

/** True when `value` is a scope this server recognises. */
export function isKnownScope(value: string): boolean {
  return KNOWN_SCOPES.includes(value);
}

/** Splits an OAuth space-delimited scope string, dropping empties. */
export function parseScopeString(raw: string | undefined): string[] {
  if (!raw) return [];
  return raw.split(/\s+/).filter(Boolean);
}

export function formatScopeString(scopes: readonly string[]): string {
  return scopes.join(' ');
}

/**
 * Narrows a requested scope set to what is both recognised and permitted.
 * Unknown scopes are a hard error (`invalid_scope`) rather than being silently
 * dropped, so a client asking for something we don't model learns about it
 * instead of silently receiving less authority than it thinks it has.
 */
export function assertScopesAllowed(
  requested: readonly string[],
  allowed: readonly string[],
): readonly string[] {
  for (const scope of requested) {
    if (!isKnownScope(scope)) {
      throw new OAuthError('invalid_scope', `Unknown scope "${scope}"`);
    }
    if (!allowed.includes(scope)) {
      throw new OAuthError('invalid_scope', `Scope "${scope}" is not permitted for this client`);
    }
  }
  return requested;
}

const LOOPBACK_HOSTS = new Set(['127.0.0.1', '::1', '[::1]', 'localhost']);

/**
 * A parsed absolute URI. The domain compiles against `lib: ES2023` alone — no
 * DOM, no Node — so there is no `URL` here to lean on. That constraint is the
 * point: redirect-URI *policy* belongs in the domain, and hand-parsing keeps it
 * there without dragging a runtime global into the dependency-free core.
 */
interface ParsedUri {
  readonly scheme: string;
  readonly host: string;
  readonly port: string;
  readonly path: string;
  readonly query: string;
  readonly fragment: string;
}

// RFC 3986 Appendix B, with the authority split out into host and port.
const URI_RE = /^([A-Za-z][A-Za-z0-9+.-]*):(\/\/([^/?#]*))?([^?#]*)(\?[^#]*)?(#.*)?$/;

function parseUri(raw: string): ParsedUri | null {
  const m = URI_RE.exec(raw);
  if (!m) return null;
  const authority = m[3] ?? '';
  // Strip any userinfo before splitting host:port; a bracketed IPv6 literal
  // keeps its brackets so "[::1]:8080" splits on the *last* colon safely.
  const hostport = authority.includes('@')
    ? authority.slice(authority.indexOf('@') + 1)
    : authority;
  let host = hostport;
  let port = '';
  const colon = hostport.lastIndexOf(':');
  if (colon !== -1 && hostport.indexOf(']', colon) === -1) {
    host = hostport.slice(0, colon);
    port = hostport.slice(colon + 1);
  }
  return {
    scheme: (m[1] ?? '').toLowerCase(),
    host: host.toLowerCase(),
    port,
    path: m[4] ?? '',
    query: m[5] ?? '',
    fragment: m[6] ?? '',
  };
}

function isLoopback(uri: ParsedUri): boolean {
  return LOOPBACK_HOSTS.has(uri.host);
}

/**
 * Validates a redirect URI at **registration** time.
 *
 * Permitted: `https://…`; `http://` only for loopback (RFC 8252 §7.3, native
 * apps); and private-use schemes containing a dot (`com.example.app:/cb`).
 * Fragments are always rejected (RFC 6749 §3.1.2).
 */
export function assertRegisterableRedirectUri(raw: string): void {
  const uri = parseUri(raw);
  if (!uri) {
    throw new OAuthError('invalid_redirect_uri', `"${raw}" is not an absolute URI`);
  }
  if (uri.fragment) {
    throw new OAuthError('invalid_redirect_uri', 'Redirect URIs must not contain a fragment');
  }
  if (uri.scheme === 'https') return;
  if (uri.scheme === 'http' && isLoopback(uri)) return;
  // Private-use URI scheme for native apps, e.g. "com.example.app:/callback".
  if (uri.scheme.includes('.')) return;
  throw new OAuthError(
    'invalid_redirect_uri',
    `Redirect URI "${raw}" must use https, a loopback http address, or a private-use scheme`,
  );
}

/**
 * Resolves the redirect URI for an authorization request against the client's
 * registered set.
 *
 * Matching is exact, with one exception mandated by RFC 8252 §7.3: for loopback
 * addresses the **port is ignored**, because a native client binds an ephemeral
 * port it cannot know at registration time. Everything else — scheme, host,
 * path, query — must match exactly.
 */
export function resolveRedirectUri(
  client: Pick<OAuthClient, 'redirectUris'>,
  requested: string | undefined,
): string {
  if (!requested) {
    // OAuth 2.1 requires an explicit redirect_uri whenever more than one is
    // registered; we require it always, so the parameter is never ambiguous.
    if (client.redirectUris.length === 1) return client.redirectUris[0] as string;
    throw new OAuthError('invalid_request', 'redirect_uri is required');
  }
  if (client.redirectUris.includes(requested)) return requested;

  const want = parseUri(requested);
  if (!want) {
    throw new OAuthError('invalid_redirect_uri', 'redirect_uri is not an absolute URI');
  }
  if (want.scheme === 'http' && isLoopback(want)) {
    for (const candidate of client.redirectUris) {
      const have = parseUri(candidate);
      if (!have) continue;
      if (
        have.scheme === want.scheme &&
        have.host === want.host &&
        have.path === want.path &&
        have.query === want.query
      ) {
        return requested;
      }
    }
  }
  throw new OAuthError('invalid_redirect_uri', 'redirect_uri does not match a registered value');
}

export interface ClientRegistrationInput {
  readonly clientName?: string;
  readonly redirectUris?: readonly string[];
  readonly grantTypes?: readonly string[];
  readonly responseTypes?: readonly string[];
  readonly tokenEndpointAuthMethod?: string;
  readonly scope?: string;
  readonly clientUri?: string;
  readonly logoUri?: string;
  readonly softwareId?: string;
}

/** The registration request after validation and defaulting. */
export interface NormalizedRegistration {
  readonly clientName: string;
  readonly redirectUris: readonly string[];
  readonly grantTypes: readonly OAuthGrantType[];
  readonly scopes: readonly string[];
  readonly tokenEndpointAuthMethod: OAuthAuthMethod;
  readonly clientUri?: string;
  readonly logoUri?: string;
  readonly softwareId?: string;
}

/**
 * Validates and normalizes an RFC 7591 dynamic client registration.
 *
 * `maxScopes` bounds what unauthenticated registration may ever ask for — an
 * anonymous client must not be able to register itself for `space:admin` and
 * then merely wait for a careless human to click approve.
 */
export function normalizeClientRegistration(
  input: ClientRegistrationInput,
  maxScopes: readonly string[],
): NormalizedRegistration {
  const clientName = input.clientName?.trim();
  if (!clientName) {
    throw new OAuthError('invalid_client_metadata', 'client_name is required');
  }

  const grantTypes = (input.grantTypes?.length ? input.grantTypes : ['authorization_code']).map(
    (g) => {
      if (!(OAUTH_GRANT_TYPES as readonly string[]).includes(g)) {
        throw new OAuthError('invalid_client_metadata', `Unsupported grant_type "${g}"`);
      }
      return g as OAuthGrantType;
    },
  );

  for (const responseType of input.responseTypes ?? []) {
    if (responseType !== 'code') {
      throw new OAuthError(
        'invalid_client_metadata',
        `Unsupported response_type "${responseType}" — only "code" is available`,
      );
    }
  }

  const redirectUris = input.redirectUris ?? [];
  // The device flow has no redirect; every other grant does.
  const needsRedirect = grantTypes.includes('authorization_code');
  if (needsRedirect && redirectUris.length === 0) {
    throw new OAuthError(
      'invalid_redirect_uri',
      'redirect_uris is required for the authorization_code grant',
    );
  }
  for (const uri of redirectUris) assertRegisterableRedirectUri(uri);

  const method = (input.tokenEndpointAuthMethod ?? 'none') as OAuthAuthMethod;
  if (!(OAUTH_AUTH_METHODS as readonly string[]).includes(method)) {
    throw new OAuthError(
      'invalid_client_metadata',
      `Unsupported token_endpoint_auth_method "${method}"`,
    );
  }

  // A client that asks for nothing at registration (as MCP clients commonly do, choosing scopes
  // at authorization instead) may later ask for anything under the ceiling. That is no grant of
  // authority: the person approving sees every scope, and a token never exceeds their role.
  const requested = parseScopeString(input.scope);
  const scopes = requested.length ? assertScopesAllowed(requested, maxScopes) : maxScopes;

  return {
    clientName,
    redirectUris,
    grantTypes,
    scopes,
    tokenEndpointAuthMethod: method,
    clientUri: input.clientUri,
    logoUri: input.logoUri,
    softwareId: input.softwareId,
  };
}

/**
 * Verifies a PKCE code verifier against the stored challenge.
 *
 * `sha256Base64Url` is injected rather than imported so this module stays free
 * of any runtime dependency. Only S256 is accepted.
 */
export function verifyPkce(
  challenge: string,
  method: string,
  verifier: string | undefined,
  sha256Base64Url: (value: string) => string,
): void {
  if (method !== PKCE_METHOD_S256) {
    throw new OAuthError('invalid_grant', 'Unsupported code_challenge_method');
  }
  if (!verifier) {
    throw new OAuthError('invalid_request', 'code_verifier is required');
  }
  // RFC 7636 §4.1 — 43..128 characters from the unreserved set.
  if (verifier.length < 43 || verifier.length > 128 || !/^[A-Za-z0-9\-._~]+$/.test(verifier)) {
    throw new OAuthError('invalid_grant', 'code_verifier is malformed');
  }
  if (sha256Base64Url(verifier) !== challenge) {
    throw new OAuthError('invalid_grant', 'code_verifier does not match the code_challenge');
  }
}

/** Rejects an authorization request that omits PKCE. Mandatory in OAuth 2.1. */
export function assertPkcePresent(challenge: string | undefined, method: string | undefined): void {
  if (!challenge) {
    throw new OAuthError('invalid_request', 'code_challenge is required (PKCE is mandatory)');
  }
  if ((method ?? PKCE_METHOD_S256) !== PKCE_METHOD_S256) {
    throw new OAuthError(
      'invalid_request',
      'code_challenge_method must be S256 — "plain" is not accepted',
    );
  }
}

/**
 * Device-flow user codes. The alphabet omits vowels (so no code spells a word)
 * and the visually ambiguous 0/O/1/I/L, because a human retypes this from one
 * screen onto another.
 */
export const USER_CODE_ALPHABET = 'BCDFGHJKMNPQRSTVWXZ23456789';
export const USER_CODE_LENGTH = 8;

/**
 * Canonicalizes a user-entered device code: uppercase, drop anything outside
 * the alphabet (so hyphens, spaces and typo'd punctuation are forgiven), then
 * re-group as `XXXX-XXXX`.
 */
export function normalizeUserCode(raw: string): string {
  const cleaned = [...raw.toUpperCase()].filter((ch) => USER_CODE_ALPHABET.includes(ch)).join('');
  if (cleaned.length !== USER_CODE_LENGTH) {
    throw new OAuthError('invalid_grant', 'That code is not valid. Check it and try again.');
  }
  return `${cleaned.slice(0, 4)}-${cleaned.slice(4)}`;
}

/** RFC 8414 authorization server metadata. */
export interface AuthorizationServerMetadata {
  readonly issuer: string;
  readonly authorization_endpoint: string;
  readonly token_endpoint: string;
  readonly registration_endpoint: string;
  readonly revocation_endpoint: string;
  readonly device_authorization_endpoint: string;
  readonly scopes_supported: readonly string[];
  readonly response_types_supported: readonly string[];
  readonly grant_types_supported: readonly string[];
  readonly code_challenge_methods_supported: readonly string[];
  readonly token_endpoint_auth_methods_supported: readonly string[];
}

/** Builds the `/.well-known/oauth-authorization-server` document. */
export function authorizationServerMetadata(issuer: string): AuthorizationServerMetadata {
  const base = issuer.replace(/\/$/, '');
  return {
    issuer: base,
    authorization_endpoint: `${base}/oauth/authorize`,
    token_endpoint: `${base}/oauth/token`,
    registration_endpoint: `${base}/oauth/register`,
    revocation_endpoint: `${base}/oauth/revoke`,
    device_authorization_endpoint: `${base}/oauth/device_authorization`,
    scopes_supported: KNOWN_SCOPES,
    response_types_supported: ['code'],
    grant_types_supported: [...OAUTH_GRANT_TYPES],
    code_challenge_methods_supported: [PKCE_METHOD_S256],
    token_endpoint_auth_methods_supported: [...OAUTH_AUTH_METHODS],
  };
}

/** RFC 9728 protected resource metadata. */
export interface ProtectedResourceMetadata {
  readonly resource: string;
  readonly authorization_servers: readonly string[];
  readonly scopes_supported: readonly string[];
  readonly bearer_methods_supported: readonly string[];
}

/** Builds the `/.well-known/oauth-protected-resource` document. */
export function protectedResourceMetadata(
  resource: string,
  issuer: string,
): ProtectedResourceMetadata {
  return {
    resource: resource.replace(/\/$/, ''),
    authorization_servers: [issuer.replace(/\/$/, '')],
    scopes_supported: KNOWN_SCOPES,
    bearer_methods_supported: ['header'],
  };
}

export const RESOURCE_METADATA_WELL_KNOWN = '/.well-known/oauth-protected-resource';

/**
 * The URL a protected resource's metadata lives at (RFC 9728 §3.1).
 *
 * The well-known segment is inserted **between the host and the path**, not
 * appended to it: a resource of `https://host/mcp` publishes its metadata at
 * `https://host/.well-known/oauth-protected-resource/mcp`. Appending instead
 * (`https://host/mcp/.well-known/…`) points clients at a 404.
 */
export function resourceMetadataUrl(resource: string): string {
  const uri = parseUri(resource);
  if (!uri) return `${resource.replace(/\/$/, '')}${RESOURCE_METADATA_WELL_KNOWN}`;
  const authority = uri.port ? `${uri.host}:${uri.port}` : uri.host;
  const path = uri.path.replace(/\/$/, '');
  return `${uri.scheme}://${authority}${RESOURCE_METADATA_WELL_KNOWN}${path}`;
}

/**
 * The path component of {@link resourceMetadataUrl} — what a server routes on.
 * Returned alongside the bare well-known path, because clients in the wild
 * probe both and serving only one strands half of them.
 */
export function resourceMetadataPaths(resource: string): readonly string[] {
  const uri = parseUri(resource);
  const path = uri ? uri.path.replace(/\/$/, '') : '';
  return path
    ? [`${RESOURCE_METADATA_WELL_KNOWN}${path}`, RESOURCE_METADATA_WELL_KNOWN]
    : [RESOURCE_METADATA_WELL_KNOWN];
}

/**
 * The `WWW-Authenticate` challenge a protected resource returns on 401 so an
 * MCP client can discover where to authenticate (RFC 9728 §5.1).
 */
export function bearerChallenge(metadataUrl: string, description?: string): string {
  const parts = [`Bearer resource_metadata="${metadataUrl}"`];
  if (description) parts.push(`error="invalid_token", error_description="${description}"`);
  return parts.join(', ');
}
