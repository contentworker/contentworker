import { describe, expect, it } from 'vitest';
import {
  createWxrImportSource,
  MAX_PAYLOAD_BYTES,
  structuredImportSources,
} from '../../src/import-structured/index';
import { parseXml } from '../../src/import-structured/xml';

const wxr = createWxrImportSource();

/** One item, with WordPress's defaults for whatever a test does not set. */
function item(over: Record<string, string> = {}, extra = ''): string {
  const v = {
    id: '10',
    title: 'Hello world',
    slug: 'hello-world',
    content: '<!-- wp:paragraph --><p>Hi &amp; welcome</p><!-- /wp:paragraph -->',
    type: 'post',
    status: 'publish',
    gmt: '2024-03-05 14:30:00',
    local: '2024-03-05 09:30:00',
    creator: 'jdoe',
    parent: '0',
    ...over,
  };
  return `
  <item>
    <title><![CDATA[${v.title}]]></title>
    <link>https://example.com/?p=${v.id}</link>
    <dc:creator><![CDATA[${v.creator}]]></dc:creator>
    <content:encoded><![CDATA[${v.content}]]></content:encoded>
    <excerpt:encoded><![CDATA[]]></excerpt:encoded>
    <wp:post_id>${v.id}</wp:post_id>
    <wp:post_date><![CDATA[${v.local}]]></wp:post_date>
    <wp:post_date_gmt><![CDATA[${v.gmt}]]></wp:post_date_gmt>
    <wp:post_name><![CDATA[${v.slug}]]></wp:post_name>
    <wp:status><![CDATA[${v.status}]]></wp:status>
    <wp:post_parent>${v.parent}</wp:post_parent>
    <wp:menu_order>0</wp:menu_order>
    <wp:post_type><![CDATA[${v.type}]]></wp:post_type>
    <wp:is_sticky>0</wp:is_sticky>
    ${extra}
  </item>`;
}

function exportOf(items: string, channelExtra = ''): string {
  return `<?xml version="1.0" encoding="UTF-8" ?>
<!-- This is a WordPress eXtended RSS file generated by WordPress as an export of your site. -->
<rss version="2.0"
  xmlns:excerpt="http://wordpress.org/export/1.2/excerpt/"
  xmlns:content="http://purl.org/rss/1.0/modules/content/"
  xmlns:dc="http://purl.org/dc/elements/1.1/"
  xmlns:wp="http://wordpress.org/export/1.2/">
<channel>
  <title>Example</title>
  <wp:wxr_version>1.2</wp:wxr_version>
  <wp:author>
    <wp:author_login><![CDATA[jdoe]]></wp:author_login>
    <wp:author_display_name><![CDATA[Jane Doe]]></wp:author_display_name>
  </wp:author>
  ${channelExtra}
  ${items}
</channel>
</rss>`;
}

describe('reading a WordPress export', () => {
  it('reads a post as flat, mappable fields', async () => {
    const result = await wxr.read(exportOf(item()));
    expect(result.records).toHaveLength(1);
    expect(result.records[0]).toMatchObject({
      externalId: '10',
      kind: 'post',
      values: {
        id: '10',
        title: 'Hello world',
        slug: 'hello-world',
        status: 'publish',
        date: '2024-03-05T14:30:00Z',
        author: 'jdoe',
        authorName: 'Jane Doe',
        link: 'https://example.com/?p=10',
        parentId: '',
      },
    });
  });

  it('keeps the post body as the HTML WordPress stored', async () => {
    // Converting is the pipeline's job, and only when the target is rich text:
    // mapped to a Text field, the HTML is what someone asked for.
    const result = await wxr.read(exportOf(item()));
    expect(result.records[0]?.values.content).toBe(
      '<!-- wp:paragraph --><p>Hi &amp; welcome</p><!-- /wp:paragraph -->',
    );
  });

  it('offers every base field even when the posts leave it empty', async () => {
    const result = await wxr.read(exportOf(item()));
    expect(result.fields).toEqual(
      expect.arrayContaining([
        'title',
        'content',
        'excerpt',
        'categories',
        'tags',
        'featuredImage',
      ]),
    );
  });

  it('separates categories, tags and custom taxonomies', async () => {
    const terms = `
      <category domain="category" nicename="news"><![CDATA[News]]></category>
      <category domain="post_tag" nicename="a"><![CDATA[Alpha]]></category>
      <category domain="post_tag" nicename="b"><![CDATA[Beta]]></category>
      <category domain="genre" nicename="jazz"><![CDATA[Jazz]]></category>`;
    const result = await wxr.read(exportOf(item({}, terms)));
    expect(result.records[0]?.values).toMatchObject({
      categories: ['News'],
      tags: ['Alpha', 'Beta'],
      'terms.genre': ['Jazz'],
    });
    expect(result.fields).toContain('terms.genre');
  });

  it('carries custom fields, and leaves out WordPress bookkeeping', async () => {
    const meta = (key: string, value: string) =>
      `<wp:postmeta><wp:meta_key><![CDATA[${key}]]></wp:meta_key><wp:meta_value><![CDATA[${value}]]></wp:meta_value></wp:postmeta>`;
    const result = await wxr.read(
      exportOf(
        item(
          {},
          meta('subtitle', 'A tale') +
            meta('_edit_lock', '1700:1') +
            meta('_seo_desc', 'For search'),
        ),
      ),
    );
    const values = result.records[0]?.values ?? {};
    expect(values['meta.subtitle']).toBe('A tale');
    // A plugin's underscore key can be real content; the report lists it as
    // unmapped and the operator decides.
    expect(values['meta._seo_desc']).toBe('For search');
    expect(values['meta._edit_lock']).toBeUndefined();
  });

  it('resolves a featured image to the attachment’s URL', async () => {
    const attachment = item({ id: '99', type: 'attachment', status: 'inherit' }).replace(
      '</item>',
      '<wp:attachment_url><![CDATA[https://example.com/cat.jpg]]></wp:attachment_url></item>',
    );
    const post = item(
      {},
      '<wp:postmeta><wp:meta_key>_thumbnail_id</wp:meta_key><wp:meta_value>99</wp:meta_value></wp:postmeta>',
    );
    const result = await wxr.read(exportOf(attachment + post));
    expect(result.records).toHaveLength(1);
    expect(result.records[0]?.values.featuredImage).toBe('https://example.com/cat.jpg');
  });

  it('resolves a featured image whose attachment comes later in the export', async () => {
    // Exports are ordered by id, and the image is often uploaded after the post.
    const attachment = item({ id: '99', type: 'attachment', status: 'inherit' }).replace(
      '</item>',
      '<wp:attachment_url>https://example.com/late.jpg</wp:attachment_url></item>',
    );
    const post = item(
      {},
      '<wp:postmeta><wp:meta_key>_thumbnail_id</wp:meta_key><wp:meta_value>99</wp:meta_value></wp:postmeta>',
    );
    const result = await wxr.read(exportOf(post + attachment));
    expect(result.records[0]?.values.featuredImage).toBe('https://example.com/late.jpg');
  });

  it('leaves the featured image empty when its attachment is not in the export', async () => {
    const post = item(
      {},
      '<wp:postmeta><wp:meta_key>_thumbnail_id</wp:meta_key><wp:meta_value>404</wp:meta_value></wp:postmeta>',
    );
    const result = await wxr.read(exportOf(post));
    const values = result.records[0]?.values ?? {};
    expect(values.featuredImage).toBe('');
    expect(values['meta._thumbnail_id']).toBeUndefined();
    expect(result.warnings).toContain(
      '1 featured image(s) point at attachments not in this export; they are left empty',
    );
  });

  it('uses a configured identity field, and numbers posts that carry no id', async () => {
    const two = exportOf(item({ id: '', slug: 'first' }) + item({ id: '', slug: 'second' }));
    expect(
      (await wxr.read(two, { identityField: 'slug' })).records.map((r) => r.externalId),
    ).toEqual(['first', 'second']);
    // Position is the visible last resort, so a report shows it is not a real id.
    expect((await wxr.read(two)).records.map((r) => r.externalId)).toEqual(['row-1', 'row-2']);
  });

  it('treats an item with no post type as a post', async () => {
    const untyped = item().replace(/<wp:post_type>.*<\/wp:post_type>/, '');
    const result = await wxr.read(exportOf(untyped));
    expect(result.records[0]?.kind).toBe('post');
  });

  it('falls back to the local date when WordPress never set the GMT one', async () => {
    const result = await wxr.read(exportOf(item({ status: 'draft', gmt: '0000-00-00 00:00:00' })));
    expect(result.records[0]?.values.date).toBe('2024-03-05T09:30:00');
  });
});

describe('choosing what to read', () => {
  const mixed = exportOf(
    item({ id: '1' }) +
      item({ id: '2', type: 'page' }) +
      item({ id: '3', type: 'page' }) +
      item({ id: '4', type: 'nav_menu_item' }),
  );

  it('reads posts by default and names what it passed over', async () => {
    const result = await wxr.read(mixed);
    expect(result.records.map((r) => r.externalId)).toEqual(['1']);
    // An export where the pages silently did not come across is the failure.
    expect(result.warnings).toEqual([
      'Not read (other post types): page (2), nav_menu_item (1). Set the postType source option to import them.',
    ]);
  });

  it('reads another post type, or several, when asked', async () => {
    expect((await wxr.read(mixed, { postType: 'page' })).records.map((r) => r.externalId)).toEqual([
      '2',
      '3',
    ]);
    expect(
      (await wxr.read(mixed, { postType: ['post', 'page'] })).records.map((r) => r.externalId),
    ).toEqual(['1', '2', '3']);
  });

  it('offers the attachment URL only when attachments are being read', async () => {
    expect((await wxr.read(mixed)).fields).not.toContain('attachmentUrl');
    expect((await wxr.read(mixed, { postType: 'attachment' })).fields).toContain('attachmentUrl');
  });

  it('leaves out abandoned drafts and the trash unless asked', async () => {
    const statuses = exportOf(
      item({ id: '1' }) +
        item({ id: '2', status: 'auto-draft' }) +
        item({ id: '3', status: 'trash' }) +
        item({ id: '4', status: 'draft' }),
    );
    const result = await wxr.read(statuses);
    expect(result.records.map((r) => r.externalId)).toEqual(['1', '4']);
    expect(result.warnings).toEqual(['Not read (status): auto-draft (1), trash (1)']);

    const onlyTrash = await wxr.read(statuses, { statuses: ['trash'] });
    expect(onlyTrash.records.map((r) => r.externalId)).toEqual(['3']);
  });

  it('says comments are not coming across', async () => {
    const comment = '<wp:comment><wp:comment_id>1</wp:comment_id></wp:comment>';
    const result = await wxr.read(exportOf(item({}, comment + comment)));
    expect(result.warnings).toContain('2 comment(s) are in the export; comments are not imported');
  });

  it('refuses an option of the wrong shape rather than reading nothing', async () => {
    await expect(wxr.read(mixed, { postType: 7 })).rejects.toThrow(/postType/);
    await expect(wxr.read(mixed, { postType: [''] })).rejects.toThrow(/postType/);
    await expect(wxr.read(mixed, { statuses: [1] })).rejects.toThrow(/statuses/);
    await expect(wxr.read(mixed, { identityField: 3 })).rejects.toThrow(/identityField/);
    expect((await wxr.read(mixed, { statuses: 'publish' })).records).toHaveLength(1);
  });
});

describe('what is not a WordPress export', () => {
  it('refuses a plain RSS feed', async () => {
    // A feed has no post ids or statuses; importing one would "work" and
    // leave nothing a re-run could recognise.
    const feed = '<rss version="2.0"><channel><item><title>x</title></item></channel></rss>';
    await expect(wxr.read(feed)).rejects.toThrow(/Not a WordPress export/);
  });

  it('says a cut-off file is probably truncated', async () => {
    const whole = exportOf(item());
    await expect(wxr.read(whole.slice(0, whole.length - 40))).rejects.toThrow(/truncated/);
  });

  it('refuses an export over the size cap before reading it', async () => {
    await expect(wxr.read(' '.repeat(MAX_PAYLOAD_BYTES + 1))).rejects.toThrow(/exceeds/);
  });

  it('is registered alongside the other sources', () => {
    expect(structuredImportSources().wxr?.name).toBe('WordPress (WXR)');
  });
});

describe('the XML reader', () => {
  it('joins CDATA sections WordPress splits around a literal "]]>"', () => {
    const root = parseXml('<a><![CDATA[x]]]]><![CDATA[>y]]></a>');
    expect(root.text).toBe('x]]>y');
  });

  it('decodes character references and the predefined entities', () => {
    expect(parseXml('<a>&lt;b&gt; &amp; &#233;&#x2014;</a>').text).toBe('<b> & é—');
    expect(parseXml(`<a t='&quot;q&quot;'/>`).attributes.t).toBe('"q"');
  });

  it('never defines entities a document type declares', () => {
    // An internal subset is how XML expands into gigabytes or reads a local
    // file. It is skipped, so its entities are simply never expanded.
    const hostile = '<!DOCTYPE a [<!ENTITY x "boom">]><a>&x;</a>';
    expect(parseXml(hostile).text).toBe('&x;');
  });

  it('skips a document type whose quoted literals hold brackets', () => {
    expect(parseXml('<!DOCTYPE x [ <!ENTITY e "]>"> ]><a>ok</a>').text).toBe('ok');
  });

  it('refuses a second root element, and text outside the root', () => {
    expect(() => parseXml('<a/>\n<b/>')).toThrow(/More than one root element \(line 2\)/);
    expect(() => parseXml('<a/>stray')).toThrow(/Text outside the root element/);
  });

  it('leaves an HTML entity outside CDATA as written rather than failing the file', () => {
    // A site title saved with &nbsp; should not block a migration.
    expect(parseXml('<a>Caf&eacute;&nbsp;Bar</a>').text).toBe('Caf&eacute;&nbsp;Bar');
  });

  it('refuses an attribute with no name', () => {
    expect(() => parseXml('<a ="3"/>')).toThrow(/Attribute with no name/);
  });

  it('names the line of a mismatched tag', () => {
    expect(() => parseXml('<a>\n<b>\n</c></a>')).toThrow(
      /Expected <\/b> but found <\/c> \(line 3\)/,
    );
  });
});
