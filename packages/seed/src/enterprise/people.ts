/** The newsroom's bylines for the firm itself. */
const CORPORATE = [
  { slug: 'aldermoor-global', name: `${BRAND.name} Global`, office: 'london' },
  { slug: 'aldermoor-americas', name: `${BRAND.name} Americas`, office: 'new-york' },
  { slug: 'aldermoor-emeia', name: `${BRAND.name} EMEIA`, office: 'london' },
] as const;

/** Offices first (people link to them), each with its opening hours and legal entity. */
export async function seedEnterpriseOffices(run: EnterpriseRun): Promise<void> {
  const { space } = run;
  const terms = await loadTerms(run);
  const files = await assetIdsByFile(run);
  const specs: Spec[] = OFFICES.map((o) => {
    const photo = o.photo ? files.get(o.photo) : undefined;
    return {
      key: o.slug,
      concepts: [region(o.area)],
      fields: {
        name: loc(o.name, space),
        slug: one(o.slug, space),
        countryCode: one(o.country, space),
        city: loc(o.city, space),
        ...(o.region ? { region: one(o.region, space) } : {}),
        address: loc(o.address, space),
        postalCode: one(o.postal, space),
        geo: one({ lat: o.lat, lon: o.lon }, space),
        phones: one([o.phone], space),
        timeZone: one(o.tz, space),
        legalEntities: one([o.entity], space),
        ...(photo ? { photo: one(asset(photo), space) } : {}),
        openingHours: one(o.country === 'AE' ? '08:00' : '08:30', space),
        closingHours: one(o.country === 'AE' ? '17:00' : '18:00', space),
      },
    };
  });
  await ensureEntries(run, 'office', specs, terms);
}

/** Corporate bylines, then people: each linked to an office, a photo when there is one. */
/** Corporate bylines and the people in `PEOPLE[from, to)`: the people split across two phases. */
export async function seedEnterprisePeople(
  run: EnterpriseRun,
  from: number,
  to: number,
): Promise<void> {
  const { space } = run;
  const terms = await loadTerms(run);
  const files = await assetIdsByFile(run);
  const offices = await keysOf(run, 'office');
  const placeholder = files.get('portrait-placeholder.png');

  const corporate: Spec[] = CORPORATE.map((c) => ({
    key: c.slug,
    fields: {
      displayName: one(c.name, space),
      slug: one(c.slug, space),
      jobTitle: loc({ en: 'Corporate communications' }, space),
      corporateAuthor: one(true, space),
      scope: one('global', space),
      office: one(entry(need(offices, c.office, 'office')), space),
    },
  }));

  const people: Spec[] = PEOPLE.slice(from, to).map((person, k) => {
    const n = from + k;
    const photo = person.photo ? files.get(person.photo) : placeholder;
    const display = person.display ?? `${person.given} ${person.family}`;
    const officeId = need(offices, person.office, 'office');
    const bio = doc(
      p(
        `${display} is ${(person.title.en as string).replace(/^(.)/, (c) => c.toLowerCase())} at ${BRAND.name}, based in ${OFFICES.find((o) => o.slug === person.office)?.city.en}. `,
        `${person.given} advises boards and executive teams on ${person.focus.join(' and ').replace(/-/g, ' ')}, `,
        'and has led programmes for clients across ',
        b(pickOf(['four continents', 'twelve markets', 'the region', 'three sectors'], n)),
        '.',
      ),
      p(
        `Before joining ${BRAND.name}, ${person.given} spent ${8 + (n % 9)} years in industry and the public sector. `,
        `${person.given} speaks ${person.languages.join(', ')}.`,
      ),
    );
    return {
      key: person.slug,
      status: person.status ?? (n % 9 === 4 ? 'changed' : 'published'),
      concepts: person.focus.map(topic),
      tags: person.scope === 'global' ? ['global-rollout'] : ['local-only'],
      fields: {
        displayName: one(display, space),
        slug: one(person.slug, space),
        givenName: one(person.given, space),
        familyName: one(person.family, space),
        nameOrder: one(person.familyFirst ? 'family-given' : 'given-family', space),
        jobTitle: loc(person.title, space),
        ...(person.tagline ? { tagline: loc(person.tagline, space) } : {}),
        ...(photo ? { photo: one(asset(photo), space) } : {}),
        ...(person.status === 'draft' ? {} : { bio: { [space.defaultLocale]: bio } }),
        office: one(entry(officeId), space),
        scope: one(person.scope, space),
        ...(person.market ? { homeMarket: one(person.market, space) } : {}),
        email: one(BRAND_EMAIL(person.slug.replace(/-/g, '.')), space),
        phone: one(e164(OFFICES.find((o) => o.slug === person.office)?.phone ?? ''), space),
        linkedIn: one(`https://www.linkedin.example/in/${person.slug}`, space),
        languages: one([...person.languages], space),
        area: one(person.scope === 'global' ? 'global' : areaOf(person.office), space),
      },
      patch: {
        tagline: loc(
          { en: `${person.given} joined the ${BRAND.name} Institute advisory board this year.` },
          space,
        ),
      },
    };
  });

  await ensureEntries(run, 'person', [...(from === 0 ? corporate : []), ...people], terms);
}

function areaOf(office: string): string {
  const a = OFFICES.find((o) => o.slug === office)?.area ?? '';
  if (['us', 'ca', 'latam'].includes(a)) return 'americas';
  if (['jp', 'greater-china', 'sea', 'oceania'].includes(a)) return 'apac';
  return 'emeia';
}

/** People slugs by focus topic, so content can credit the right experts. */
export function expertsOn(topicSlug: string): string[] {
  return PEOPLE.filter((x) => x.focus.includes(topicSlug) && x.status !== 'draft').map(
    (x) => x.slug,
  );
}
