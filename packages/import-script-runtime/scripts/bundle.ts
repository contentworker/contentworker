/**
 * Bundles the runtime (src/run.ts, the parsed page and linkedom) into one ES module, embedded as
 * a string in src/bundle.generated.ts.
 *
 * The Worker Loader sandbox takes its modules as source text, and a Worker has no filesystem to
 * read linkedom from, so the runtime travels with the host Worker as a string and is handed to
 * every sandbox it loads. Its hash is part of the sandbox's cache key, so a changed runtime never
 * reuses an isolate warmed with the old one.
 *
 * The output is gitignored, never committed. `pnpm install` runs this as postinstall, and turbo's
 * `generate` task reruns it before every check-types, test, build and dev.
 */
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'src', 'bundle.generated.ts');
// linkedom's package root (its `exports` hide the shim's path, not the file).
const linkedom = dirname(dirname(createRequire(import.meta.url).resolve('linkedom')));

export async function bundle(): Promise<string> {
  const result = await build({
    entryPoints: [join(here, '..', 'src', 'run.ts')],
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2023',
    minify: true,
    // Error names and stack frames stay readable for the script's author.
    keepNames: true,
    write: false,
    legalComments: 'none',
    // linkedom asks for the native `canvas` package and falls back to its shim when it is
    // missing; nothing in a sandbox draws, so bundle the shim in its place.
    alias: { canvas: join(linkedom, 'commonjs', 'canvas-shim.cjs') },
    mainFields: ['module', 'main'],
    conditions: ['import', 'default'],
  });
  const file = result.outputFiles[0];
  if (!file) throw new Error('esbuild produced no output');
  return file.text;
}

export function buildSource(code: string): string {
  const hash = createHash('sha256').update(code).digest('hex').slice(0, 16);
  return [
    '// GENERATED by scripts/bundle.ts — do not edit.',
    '// Run `pnpm --filter @contentworker/import-script-runtime generate` after editing src/.',
    '',
    '/** The runtime as one ES module (exports `runImportScript`), for the sandbox to load. */',
    `export const IMPORT_SCRIPT_RUNTIME: string = ${JSON.stringify(code)};`,
    '',
    '/** A hash of {@link IMPORT_SCRIPT_RUNTIME}: part of every sandbox cache key. */',
    `export const IMPORT_SCRIPT_RUNTIME_HASH = ${JSON.stringify(hash)};`,
    '',
  ].join('\n');
}

writeFileSync(out, buildSource(await bundle()));
