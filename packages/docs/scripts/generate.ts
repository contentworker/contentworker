/**
 * Embeds `docs/*.md` into a TypeScript module.
 *
 * The docs have to be readable from a Cloudflare Worker, which has no
 * filesystem, and from a container image that may or may not have shipped the
 * markdown alongside the code. Embedding makes the answer identical everywhere
 * and removes the failure mode where the tools exist but find nothing. The cost
 * is bundle weight — a few hundred KB of prose, which compresses well.
 *
 * The output is gitignored, never committed (committed, it conflicted between
 * every pair of PRs that touched docs/). `pnpm install` runs this as
 * postinstall, and turbo's `generate` task reruns it before every
 * check-types, test, build and dev whenever docs/*.md changes.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const docsDir = join(here, '..', '..', '..', 'docs');
const out = join(here, '..', 'src', 'generated.ts');

export function buildSource(): string {
  const files = readdirSync(docsDir)
    .filter((f) => f.endsWith('.md'))
    .sort();
  const pages = files.map((file) => ({
    path: file.replace(/\.md$/, ''),
    body: readFileSync(join(docsDir, file), 'utf8'),
  }));
  return [
    '// GENERATED by scripts/generate.ts — do not edit.',
    '// Run `pnpm --filter @contentworker/docs generate` after editing docs/.',
    '',
    '/** Every published documentation page, keyed by its slug. */',
    'export const DOC_SOURCES: Readonly<Record<string, string>> = {',
    ...pages.map((p) => `  ${JSON.stringify(p.path)}: ${JSON.stringify(p.body)},`),
    '};',
    '',
  ].join('\n');
}

// Only when run as a script — the freshness test imports `buildSource` and must
// not rewrite the file it is checking.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(out, buildSource());
  console.log(`wrote ${out}`);
}
