// @vitest-environment jsdom
import type { ContentType } from '@contentworker/domain';
import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { MemoryRouter } from 'react-router';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { CanvasDialog } from '~/cms/components/CanvasDialog';
import type { GeneratedDraft } from '~/cms/lib/management';

globalThis.ResizeObserver ??= class {
  observe() {}
  unobserve() {}
  disconnect() {}
} as unknown as typeof ResizeObserver;

const article = {
  apiId: 'article',
  name: 'Article',
  displayField: 'title',
  fields: [
    { apiId: 'title', name: 'Title', type: 'Symbol' },
    { apiId: 'excerpt', name: 'Excerpt', type: 'Text' },
  ],
} as unknown as ContentType;

const client = {
  listTags: vi.fn(async () => []),
  summarizeEntry: vi.fn(async () => ({ summary: 'A tight summary.', applied: false })),
  translateEntry: vi.fn(async () => ({
    translatedFields: ['title'],
    fields: { title: { 'de-DE': 'Hallo' } },
    applied: false,
  })),
  autofillField: vi.fn(async () => ({ field: 'title', value: 'Filled in.', applied: false })),
  suggestEntryTags: vi.fn(async () => ({ tagIds: ['t-1', 't-2'], newTags: ['Realtime'] })),
  applyEntryTags: vi.fn(async () => ({
    tagIds: ['t-1', 't-2', 't-new'],
    createdTags: [{ id: 't-new', name: 'Realtime' }],
  })),
  relatedEntries: vi.fn(async () => [
    { entryId: 'e-rel', score: 0.71, snippet: 'Related body text' },
  ]),
  findDuplicates: vi.fn(async () => [
    { entryId: 'e-dup', score: 0.93, snippet: 'Long body '.repeat(80) },
  ]),
};

vi.mock('~/cms/lib/client-context', () => ({ useClient: () => ({ client }) }));
vi.mock('~/cms/lib/queries', () => ({
  useScopedQuery: () => ({ data: [] }),
  useInvalidate: () => async () => {},
}));

const { GenerateEntryDialog } = await import('~/cms/components/GenerateEntryDialog');
const { AiAssistPanel } = await import('~/cms/components/AiAssistPanel');
const { SemanticPanel } = await import('~/cms/components/SemanticPanel');
const { ToastProvider } = await import('~/cms/lib/toast');

afterEach(() => {
  cleanup();
  vi.clearAllMocks();
});

const draft: GeneratedDraft = {
  contentTypeApiId: 'article',
  fields: { title: { 'en-US': 'Realtime sync is here' }, excerpt: { 'en-US': 'Edits land live.' } },
  usage: { inputTokens: 100, outputTokens: 50 },
};

describe('GenerateEntryDialog', () => {
  const setup = () => {
    const onGenerate = vi.fn(async () => draft);
    const onApply = vi.fn();
    render(
      <GenerateEntryDialog
        open
        onOpenChange={() => {}}
        contentType={article}
        onGenerate={onGenerate}
        onApply={onApply}
      />,
    );
    return { onGenerate, onApply };
  };

  it('fills the prompt from a starter without submitting', () => {
    const { onGenerate } = setup();
    fireEvent.click(screen.getByRole('button', { name: 'A concise summary of' }));
    expect((screen.getByLabelText('Prompt') as HTMLTextAreaElement).value).toBe(
      'A concise summary of ',
    );
    expect(onGenerate).not.toHaveBeenCalled();
  });

  it('shows the draft as a proposal and only touches the form on Apply', async () => {
    const { onGenerate, onApply } = setup();
    fireEvent.change(screen.getByLabelText('Prompt'), { target: { value: 'Launch post' } });
    fireEvent.click(screen.getByRole('button', { name: 'Generate draft' }));

    const proposal = await screen.findByRole('alertdialog', { name: 'Apply 2 drafted fields?' });
    expect(onGenerate).toHaveBeenCalledWith('Launch post', 'balanced', expect.any(AbortSignal));
    expect(onApply).not.toHaveBeenCalled();
    expect(proposal.textContent).toContain('Realtime sync is here');
    expect(proposal.textContent).toContain('Title (en-US)');
    // Provenance: which model, how many tokens.
    expect(proposal.textContent).toContain('Generated by Balanced');
    expect(proposal.textContent).toContain('150 tokens');
    // Focus lands on the safe choice.
    expect(document.activeElement).toBe(screen.getByRole('button', { name: 'Discard' }));

    fireEvent.click(screen.getByRole('button', { name: 'Apply to form' }));
    expect(onApply).toHaveBeenCalledWith(draft.fields);
  });

  it('shows drafted blocks as an outline, and the images the library had no match for', async () => {
    const page = {
      ...article,
      fields: [
        ...article.fields,
        {
          apiId: 'body',
          name: 'Main',
          type: 'Array',
          localized: false,
          required: false,
          position: 9,
          items: {
            type: 'Component',
            variants: [
              {
                apiId: 'hero',
                name: 'Hero',
                fields: [
                  {
                    apiId: 'heading',
                    name: 'Heading',
                    type: 'Symbol',
                    localized: false,
                    required: false,
                    position: 0,
                  },
                  {
                    apiId: 'image',
                    name: 'Image',
                    type: 'Link',
                    linkType: 'Asset',
                    localized: false,
                    required: true,
                    position: 1,
                  },
                ],
              },
            ],
          },
        },
      ],
    } as unknown as ContentType;
    const withBlocks: GeneratedDraft = {
      ...draft,
      fields: {
        ...draft.fields,
        body: { 'en-US': [{ _type: 'hero', _key: 'k1', heading: 'Ship it' }] },
      },
      unresolvedImages: [{ path: 'body[0].image', query: 'a rocket at dawn', required: true }],
    };
    render(
      <GenerateEntryDialog
        open
        onOpenChange={() => {}}
        contentType={page}
        onGenerate={async () => withBlocks}
        onApply={() => {}}
      />,
    );
    fireEvent.change(screen.getByLabelText('Prompt'), { target: { value: 'A launch page' } });
    fireEvent.click(screen.getByRole('button', { name: 'Generate draft' }));
    const proposal = await screen.findByRole('alertdialog', { name: 'Apply 3 drafted fields?' });
    const outline = screen.getByRole('list', { name: 'Main (en-US): drafted blocks' });
    expect(outline.textContent).toContain('Hero');
    expect(outline.textContent).toContain('Ship it');
    // Blocks read as blocks, never as JSON.
    expect(proposal.textContent).not.toContain('"_type"');
    expect(proposal.textContent).toContain('Main › Hero 1 › Image');
    expect(proposal.textContent).toContain('“a rocket at dawn”');
    expect(proposal.textContent).toContain('required');
    expect(proposal.textContent).toContain('Choose an image for it before you save.');
    // The provenance says the library was searched (it opens on its trigger).
    fireEvent.click(screen.getByRole('button', { name: /Generated by Balanced/ }));
    expect(proposal.textContent).toContain('Looked in the library for images: no match for 1');
  });

  it('Discard drops the draft and keeps the prompt for another run', async () => {
    const { onApply } = setup();
    fireEvent.change(screen.getByLabelText('Prompt'), { target: { value: 'Launch post' } });
    fireEvent.click(screen.getByRole('button', { name: 'Generate draft' }));
    await screen.findByRole('alertdialog');
    fireEvent.click(screen.getByRole('button', { name: 'Discard' }));
    expect(screen.queryByRole('alertdialog')).toBeNull();
    expect((screen.getByLabelText('Prompt') as HTMLTextAreaElement).value).toBe('Launch post');
    expect(onApply).not.toHaveBeenCalled();
  });

  it('closing during a generation aborts it, drops a late result and keeps the prompt', async () => {
    let finish: (d: GeneratedDraft) => void = () => {};
    let signal: AbortSignal | undefined;
    const onGenerate = vi.fn((_p: string, _t: string, s: AbortSignal) => {
      signal = s;
      return new Promise<GeneratedDraft>((resolve) => {
        finish = resolve;
      });
    });
    const onOpenChange = vi.fn();
    const dialog = (open: boolean) => (
      <GenerateEntryDialog
        open={open}
        onOpenChange={onOpenChange}
        contentType={article}
        onGenerate={onGenerate}
        onApply={() => {}}
      />
    );
    const view = render(dialog(true));
    fireEvent.change(screen.getByLabelText('Prompt'), { target: { value: 'Launch post' } });
    fireEvent.click(screen.getByRole('button', { name: 'Generate draft' }));
    await screen.findByRole('button', { name: 'Generating…' });

    // Both ways out work while the model hangs.
    expect(screen.getByRole('button', { name: 'Cancel' }).hasAttribute('disabled')).toBe(false);
    fireEvent.click(screen.getByRole('button', { name: 'Close' }));
    expect(onOpenChange).toHaveBeenCalledWith(false);
    expect(signal?.aborted).toBe(true);
    view.rerender(dialog(false));

    await act(async () => finish(draft));
    view.rerender(dialog(true));

    expect(screen.queryByRole('alertdialog')).toBeNull();
    expect((screen.getByLabelText('Prompt') as HTMLTextAreaElement).value).toBe('Launch post');
    expect(screen.getByRole('button', { name: 'Generate draft' })).toBeTruthy();
  });

  it('a draft under review survives Escape and a press outside', async () => {
    const onOpenChange = vi.fn();
    const dialog = (open: boolean) => (
      <GenerateEntryDialog
        open={open}
        onOpenChange={onOpenChange}
        contentType={article}
        onGenerate={async () => draft}
        onApply={() => {}}
      />
    );
    const view = render(dialog(true));
    fireEvent.change(screen.getByLabelText('Prompt'), { target: { value: 'Launch post' } });
    fireEvent.click(screen.getByRole('button', { name: 'Generate draft' }));
    await screen.findByRole('alertdialog');

    // Focus sits on Discard, but Escape is not a decision to discard.
    fireEvent.keyDown(document.activeElement as Element, { key: 'Escape' });
    expect(onOpenChange).toHaveBeenCalledWith(false);
    view.rerender(dialog(false));
    view.rerender(dialog(true));
    expect(screen.getByRole('alertdialog', { name: 'Apply 2 drafted fields?' })).toBeTruthy();

    fireEvent.pointerDown(document.body);
    fireEvent.click(document.body);
    view.rerender(dialog(false));
    view.rerender(dialog(true));
    expect(screen.getByRole('alertdialog', { name: 'Apply 2 drafted fields?' })).toBeTruthy();
  });
});

describe('CanvasDialog', () => {
  it('closing during a mapping aborts it and keeps the prose', async () => {
    let signal: AbortSignal | undefined;
    const onMap = vi.fn((_p: string, _t: string, s: AbortSignal) => {
      signal = s;
      return new Promise<void>(() => {});
    });
    const onOpenChange = vi.fn();
    const dialog = (open: boolean) => (
      <CanvasDialog
        open={open}
        onOpenChange={onOpenChange}
        contentTypeName="Article"
        onMap={onMap}
      />
    );
    const view = render(dialog(true));
    fireEvent.change(screen.getByLabelText('Prose'), { target: { value: 'Notes' } });
    fireEvent.click(screen.getByRole('button', { name: 'Map to fields' }));
    await screen.findByRole('button', { name: 'Mapping…' });

    fireEvent.click(screen.getByRole('button', { name: 'Cancel' }));

    expect(signal?.aborted).toBe(true);
    expect(onOpenChange).toHaveBeenCalledWith(false);
    view.rerender(dialog(false));
    view.rerender(dialog(true));
    expect((screen.getByLabelText('Prose') as HTMLTextAreaElement).value).toBe('Notes');
    expect(screen.getByRole('button', { name: 'Map to fields' })).toBeTruthy();
  });
});

describe('AiAssistPanel', () => {
  const setup = (locales: string[] = ['en-US']) => {
    const onMergeFields = vi.fn();
    render(
      <ToastProvider>
        <AiAssistPanel
          entryId="e1"
          contentType={article}
          locales={locales}
          defaultLocale="en-US"
          onMergeFields={onMergeFields}
        />
      </ToastProvider>,
    );
    return { onMergeFields };
  };

  it('starts collapsed', () => {
    setup();
    expect(screen.getByRole('button', { name: /AI assist/ }).getAttribute('aria-expanded')).toBe(
      'false',
    );
    expect(screen.queryByRole('button', { name: 'Summarize' })).toBeNull();
  });

  it('renders a summary as a reviewable proposal with provenance; Apply merges it', async () => {
    const { onMergeFields } = setup();
    fireEvent.click(screen.getByRole('button', { name: /AI assist/ }));
    fireEvent.click(screen.getByRole('button', { name: 'Summarize' }));

    const proposal = await screen.findByRole('alertdialog', { name: 'Apply summary to Title?' });
    expect(onMergeFields).not.toHaveBeenCalled();
    expect(proposal.textContent).toContain('A tight summary.');
    expect(screen.getByRole('button', { name: /AI assist · Summarize → Title/ })).toBeTruthy();

    fireEvent.click(screen.getByRole('button', { name: 'Apply' }));
    await waitFor(() =>
      expect(onMergeFields).toHaveBeenCalledWith({ title: { 'en-US': 'A tight summary.' } }),
    );
    await waitFor(() => expect(screen.queryByRole('alertdialog')).toBeNull());
  });

  it('Escape dismisses a proposal without writing anything', async () => {
    const { onMergeFields } = setup();
    fireEvent.click(screen.getByRole('button', { name: /AI assist/ }));
    fireEvent.click(screen.getByRole('button', { name: 'Summarize' }));
    await screen.findByRole('alertdialog');
    fireEvent.keyDown(document.activeElement ?? document.body, { key: 'Escape' });
    expect(screen.queryByRole('alertdialog')).toBeNull();
    expect(onMergeFields).not.toHaveBeenCalled();
  });
  it('asks for proposals only: Summarize, Translate and Autofill never write server-side', async () => {
    setup(['en-US', 'de-DE']);
    fireEvent.click(screen.getByRole('button', { name: /AI assist/ }));

    fireEvent.click(screen.getByRole('button', { name: 'Summarize' }));
    await screen.findByRole('alertdialog', { name: 'Apply summary to Title?' });
    fireEvent.click(screen.getByRole('button', { name: 'Dismiss' }));

    fireEvent.click(screen.getByRole('button', { name: 'Translate' }));
    await screen.findByRole('alertdialog', { name: 'Apply 1 translated field?' });
    fireEvent.click(screen.getByRole('button', { name: 'Dismiss' }));

    fireEvent.click(screen.getByRole('button', { name: 'Autofill' }));
    await screen.findByRole('alertdialog', { name: 'Apply value to Title?' });

    expect(client.summarizeEntry).toHaveBeenCalledWith('e1', {
      targetField: 'title',
      apply: false,
    });
    expect(client.translateEntry).toHaveBeenCalledWith('e1', {
      targetLocale: 'de-DE',
      apply: false,
    });
    expect(client.autofillField).toHaveBeenCalledWith('e1', { field: 'title', apply: false });
  });

  it('applying tags persists exactly the reviewed suggestion without asking the model again', async () => {
    setup();
    fireEvent.click(screen.getByRole('button', { name: /AI assist/ }));
    fireEvent.click(screen.getByRole('button', { name: 'Suggest taxonomy tags' }));

    await screen.findByRole('alertdialog', { name: 'Apply 3 tags?' });
    expect(client.suggestEntryTags).toHaveBeenCalledExactlyOnceWith('e1', { apply: false });
    expect(client.applyEntryTags).not.toHaveBeenCalled();

    fireEvent.click(screen.getByRole('button', { name: 'Apply' }));
    await waitFor(() =>
      expect(client.applyEntryTags).toHaveBeenCalledExactlyOnceWith('e1', {
        tagIds: ['t-1', 't-2'],
        newTags: ['Realtime'],
      }),
    );
    expect(await screen.findByText('Tagged · new: Realtime')).toBeTruthy();
    expect(client.suggestEntryTags).toHaveBeenCalledOnce();
  });
});

describe('SemanticPanel', () => {
  it('shows duplicates as a collapsed, non-error line with one row per match', async () => {
    render(
      <MemoryRouter>
        <SemanticPanel
          entryId="e1"
          entries={[{ id: 'e-dup', contentType: 'article', label: 'Launch post' }]}
        />
      </MemoryRouter>,
    );
    const summary = await screen.findByRole('button', { name: /1 possible duplicate/ });
    expect(screen.queryByRole('alert')).toBeNull();
    expect(summary.getAttribute('aria-expanded')).toBe('false');
    expect(screen.queryByRole('link', { name: 'Launch post' })).toBeNull();

    fireEvent.click(summary);
    const link = screen.getByRole('link', { name: 'Launch post' });
    expect(link.getAttribute('href')).toBe('/content/article/e-dup');
    expect(screen.getByText('93% similar')).toBeTruthy();
    // The snippet stays behind its own toggle.
    expect(screen.queryByText(/Long body/)).toBeNull();
    fireEvent.click(screen.getByRole('button', { name: 'Show excerpt from Launch post' }));
    expect(screen.getByText(/Long body/)).toBeTruthy();
  });

  it('names unknown entries by a clipped opening of their snippet, never the whole thing', async () => {
    render(
      <MemoryRouter>
        <SemanticPanel entryId="e1" />
      </MemoryRouter>,
    );
    expect(await screen.findByText('“Related body text…”')).toBeTruthy();
    fireEvent.click(screen.getByRole('button', { name: /possible duplicate/ }));
    // Eight words at most in the title; the 160-word snippet stays behind its toggle.
    expect(screen.getByText('“Long body Long body Long body Long body…”')).toBeTruthy();
  });
});
